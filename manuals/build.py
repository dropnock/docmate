#!/usr/bin/env python3
"""Build the in-app manuals from Markdown + one branded template.

    python manuals/build.py [--out DIR] [--version X.Y.Z]

Reads manuals.yaml (which manuals exist, who may see them), brand/brand.yaml
(all branding) and templates/, and writes:

    DIR/web/<slug>.html     the in-app pages, plus web/assets/ and web/images/
    DIR/print/<slug>.html   the same content laid out for print; the backend
                            fills in PREPARED_FOR / ISSUED_ON and renders it
                            to PDF with WeasyPrint (base URL = DIR/web)
    DIR/manuals.json        the catalogue the backend serves

Markdown is converted with pandoc's GFM reader, the same reader
tools/build_docx.py uses for the Word copies. The build fails if a
`#anchor` link or an image doesn't resolve.

Needs: pandoc on PATH; Python packages jinja2, pyyaml.
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined
from markupsafe import Markup

HERE = Path(__file__).resolve().parent

# Filled in per download by backend/app/help/service.py. Kept as plain
# tokens (no characters HTML would escape) so a str.replace finds them.
PREPARED_FOR = "__DOCMATE_PREPARED_FOR__"
ISSUED_ON = "__DOCMATE_ISSUED_ON__"


class BuildError(Exception):
    pass


def load_yaml(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def default_version() -> str:
    env = os.environ.get("APP_VERSION")
    if env and env != "dev":
        return env
    for candidate in (HERE.parent / "VERSION", HERE / "VERSION"):
        if candidate.exists():
            return candidate.read_text().strip()
    return env or "dev"


def pandoc_html(md_path: Path) -> str:
    """Markdown -> HTML fragment. GFM reader: GitHub-style heading ids, which
    the manuals' own `[Section 7](#7-…)` links are written against. The
    workbooks' "☐" boxes are for ticking on paper, so stay characters."""
    result = subprocess.run(
        ["pandoc", str(md_path), "-f", "gfm+implicit_figures", "-t", "html5", "--wrap=none"],
        check=True, capture_output=True, text=True,
    )
    # Some pandoc versions read a leading "☐" as a task-list box regardless;
    # put the character back.
    return re.sub(r'<input type="checkbox"[^>]*/>\s*', "☐ ", result.stdout)


def strip_tags(s: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def split_front(body: str) -> tuple[str, str]:
    """Remove the leading <h1> (the template shows the title) and the
    "**For:** …" line under it, which becomes the subtitle."""
    body = re.sub(r"^\s*<h1[^>]*>.*?</h1>\s*", "", body, count=1, flags=re.S)
    subtitle = ""
    m = re.match(r"\s*<p>(<strong>For:</strong>.*?)</p>\s*", body, flags=re.S)
    if m:
        subtitle = m.group(1)
        body = body[m.end():]
    return subtitle, body


def wrap_tables(body: str) -> str:
    return re.sub(r"(<table\b.*?</table>)", r'<div class="table-wrap">\1</div>', body, flags=re.S)


def toc_from(body: str) -> list[dict]:
    return [
        {"id": m.group(1), "text": strip_tags(m.group(2))}
        for m in re.finditer(r'<h2 id="([^"]+)"[^>]*>(.*?)</h2>', body, flags=re.S)
        if m.group(1) != "contents"  # the sidebar is the contents
    ]


def check(body: str, md_path: Path) -> None:
    ids = set(re.findall(r'\sid="([^"]+)"', body))
    problems = [
        f"link to missing anchor #{a}"
        for a in sorted(set(re.findall(r'href="#([^"]+)"', body)))
        if a not in ids
    ]
    for src in sorted(set(re.findall(r'<img[^>]+src="([^"]+)"', body))):
        if not re.match(r"^[a-z]+:", src) and not (md_path.parent / src).is_file():
            problems.append(f"missing image {src}")
    if problems:
        raise BuildError(f"{md_path.name}: " + "; ".join(problems))


def brand_css(brand: dict) -> str:
    c = brand["colors"]
    font = brand["font"]
    faces = "".join(
        "@font-face { font-family: '%s'; font-weight: %s; font-style: normal; font-display: swap;"
        " src: url('fonts/%s') format('woff2'); }\n" % (font["family"], weight, Path(f).name)
        for weight, f in sorted(font["files"].items())
    )
    props = "".join(f"  --{k.replace('_', '-')}: {v};\n" for k, v in c.items())
    product_portal = json.dumps(f"{brand['product']} {brand['portal']}")
    return (
        "/* Generated by manuals/build.py from brand/brand.yaml. Don't edit. */\n"
        f"{faces}"
        ":root {\n"
        f"{props}"
        f"  --font: '{font['family']}', {font['fallback']};\n"
        f"  --product-portal: {product_portal};\n"
        "}\n"
        f"@page {{ size: {brand['page']['size']}; margin: {brand['page']['margin']}; }}\n"
    )


def build(out: Path, version: str) -> list[dict]:
    brand = load_yaml(HERE / "brand" / "brand.yaml")
    catalogue = load_yaml(HERE / "manuals.yaml")["manuals"]

    if out.exists():
        shutil.rmtree(out)
    web, printdir, assets = out / "web", out / "print", out / "web" / "assets"
    (assets / "fonts").mkdir(parents=True)
    printdir.mkdir()

    # Assets: generated brand.css, the two stylesheets, fonts, optional logo.
    (assets / "brand.css").write_text(brand_css(brand), encoding="utf-8")
    for css in ("manual.css", "print.css"):
        shutil.copy(HERE / "templates" / css, assets / css)
    for f in brand["font"]["files"].values():
        shutil.copy(HERE / "brand" / f, assets / "fonts" / Path(f).name)
    logo_file = ""
    if brand.get("logo"):
        logo_src = HERE / "brand" / brand["logo"]
        logo_file = "logo" + logo_src.suffix
        shutil.copy(logo_src, assets / logo_file)
    shutil.copytree(HERE / "content" / "images", web / "images")

    env = Environment(
        loader=FileSystemLoader(HERE / "templates"),
        autoescape=True, undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True,
    )
    template = env.get_template("base.html.j2")

    entries = []
    for manual in catalogue:
        md_path = HERE / manual["source"]
        body = pandoc_html(md_path)
        check(body, md_path)
        subtitle, body = split_front(body)
        body = wrap_tables(body)
        ctx = dict(
            brand=brand, manual=manual, version=version, logo_file=logo_file,
            subtitle=Markup(subtitle), body=Markup(body), toc=toc_from(body),
            PREPARED_FOR=PREPARED_FOR, ISSUED_ON=ISSUED_ON,
        )
        (web / f"{manual['slug']}.html").write_text(template.render(mode="web", **ctx), encoding="utf-8")
        (printdir / f"{manual['slug']}.html").write_text(template.render(mode="print", **ctx), encoding="utf-8")
        entries.append({k: manual[k] for k in ("slug", "title", "kind", "roles")})

    (out / "manuals.json").write_text(
        json.dumps({"version": version, "manuals": entries}, indent=2), encoding="utf-8"
    )
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=HERE / "dist")
    ap.add_argument("--version", default=None)
    args = ap.parse_args()
    version = args.version or default_version()
    try:
        entries = build(args.out, version)
    except BuildError as e:
        print(f"manuals build failed: {e}", file=sys.stderr)
        return 1
    print(f"built {len(entries)} manuals (v{version}) into {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
